import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('prepare', ROOT / 'scripts/prepare.py')
prepare = importlib.util.module_from_spec(spec)
spec.loader.exec_module(prepare)

class PreparationTests(unittest.TestCase):
    def test_checked_cache_and_corruption(self):
        pins = json.loads((ROOT / 'Sources/decant/Resources/RuntimePins.json').read_text())
        cache = ROOT / '.build/production-shim-preflight'
        if not (cache / pins['shim']['file']).exists():
            self.skipTest('checked cache is generated by preparation')
        import shutil
        artifact = (cache / pins['shim']['file']).read_bytes()
        definition = (cache / 'gptk-video/d3d12shim-4.0b3.def').read_text()
        prepare.check_pe(artifact, definition)
        for name in ('D3D12GetInterface', 'D3D12SerializeRootSignature', 'D3D12SerializeVersionedRootSignature'):
            encoded = name.encode() + b'\0'
            self.assertIn(encoded, artifact)
            shortened = name[5:].encode() + b'\0' * 6
            bad = artifact.replace(encoded, shortened)
            with self.assertRaisesRegex(ValueError, 'export names'):
                prepare.check_pe(bad, definition)
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            shutil.copytree(cache, root / '.build/production-shim-preflight')
            (root / 'Sources/decant/Resources').mkdir(parents=True)
            with patch.object(prepare, 'ROOT', root), patch.object(prepare.urllib.request, 'urlopen', side_effect=AssertionError('unexpected download')):
                prepare.resource(pins)
                generated = root / 'Sources/decant/Resources' / pins['shim']['file']
                pins_path = generated.parent / 'RuntimePins.json'
                pins_path.write_text(json.dumps(pins))
                prepare.check_bundle(generated.parent, pins_path)
                generated.write_bytes(b'bad resource')
                with self.assertRaisesRegex(ValueError, 'packaged shim mismatch'):
                    prepare.check_bundle(generated.parent, pins_path)
                with self.assertRaisesRegex(ValueError, 'resource mismatch'):
                    prepare.resource(pins)
                generated.unlink()
                output = root / '.build/production-shim-preflight' / pins['shim']['file']
                output.write_bytes(b'bad output')
                with self.assertRaisesRegex(ValueError, 'artifact mismatch'):
                    prepare.resource(pins)
                source = root / '.build/production-shim-preflight/gptk-video/d3d12shim.c'
                source.write_bytes(b'bad source')
                with self.assertRaisesRegex(ValueError, 'source identity'):
                    prepare.resource(pins)

    def test_malformed_pe(self):
        for data in (b'', b'MZ', b'MZ' + bytes(100)):
            with self.assertRaises(ValueError):
                prepare.check_pe(data, '')
